// Regenerates src/i18n/geo/ranges.generated.ts: the IP blocks registered to Iran and Turkey, which
// pick the site's language for a first-time visitor (see src/i18n/geo/country.ts).
// The data is RIPE NCC's public list of address allocations, so no lookup service is called at runtime.
// Run every few months:
//   npx tsx scripts/build-geo-ranges.ts
// Set RIPE_FILE=/path/to/delegated-ripencc-extended-latest to build from a file already downloaded.

import { readFileSync, writeFileSync } from 'node:fs';

const SOURCE = 'https://ftp.ripe.net/pub/stats/ripencc/delegated-ripencc-extended-latest';
const COUNTRIES = ['IR', 'TR'] as const;
const OUT = 'src/i18n/geo/ranges.generated.ts';

const ipv4ToNumber = (ip: string) => ip.split('.').reduce((total, part) => total * 256 + Number(part), 0);

// The first 64 bits of an IPv6 address; allocations are never longer than /64.
const ipv6High = (ip: string) => {
  const [head, tail = ''] = ip.split('::');
  const left = head ? head.split(':') : [];
  const right = tail ? tail.split(':') : [];
  const groups = [...left, ...Array(8 - left.length - right.length).fill('0'), ...right];
  return groups.slice(0, 4).reduce((total, group) => (total << 16n) | BigInt(parseInt(group || '0', 16)), 0n);
};

function merge(ranges: [bigint, bigint][]) {
  ranges.sort((a, b) => (a[0] < b[0] ? -1 : a[0] > b[0] ? 1 : 0));
  const merged: [bigint, bigint][] = [];
  for (const [start, end] of ranges) {
    const last = merged[merged.length - 1];
    if (last && start <= last[1] + 1n) last[1] = end > last[1] ? end : last[1];
    else merged.push([start, end]);
  }
  return merged;
}

async function main() {
  const text = process.env.RIPE_FILE ? readFileSync(process.env.RIPE_FILE, 'utf8') : await (await fetch(SOURCE)).text();
  const v4: Record<string, [bigint, bigint][]> = { IR: [], TR: [] };
  const v6: Record<string, [bigint, bigint][]> = { IR: [], TR: [] };

  for (const line of text.split('\n')) {
    const [registry, country, type, start, value, , status] = line.split('|');
    if (registry !== 'ripencc' || !COUNTRIES.includes(country as never) || !['allocated', 'assigned'].includes(status)) continue;
    if (type === 'ipv4') {
      const from = BigInt(ipv4ToNumber(start));
      v4[country].push([from, from + BigInt(value) - 1n]);
    } else if (type === 'ipv6') {
      const length = Math.min(Number(value), 64);
      const from = ipv6High(start);
      v6[country].push([from, from | ((1n << BigInt(64 - length)) - 1n)]);
    }
  }

  // Start and end of each block, base 36, flattened: "start,end,start,end,..."
  const pack = (ranges: [bigint, bigint][]) => merge(ranges).flatMap(([a, b]) => [a.toString(36), b.toString(36)]).join(',');
  const lines = [
    '// Generated by scripts/build-geo-ranges.ts from RIPE NCC allocation data. Do not edit by hand.',
    `// Built ${new Date().toISOString().slice(0, 10)}.`,
    '',
    'export const IPV4_RANGES: Record<string, string> = {',
    ...COUNTRIES.map((country) => `  ${country}: '${pack(v4[country])}',`),
    '};',
    '',
    '// The first 64 bits of each IPv6 block.',
    'export const IPV6_RANGES: Record<string, string> = {',
    ...COUNTRIES.map((country) => `  ${country}: '${pack(v6[country])}',`),
    '};',
    '',
  ];
  writeFileSync(OUT, lines.join('\n'));
  for (const country of COUNTRIES) console.log(`${country}: ${merge(v4[country]).length} IPv4 and ${merge(v6[country]).length} IPv6 blocks`);
}

main().catch((error) => {
  console.error(error);
  process.exit(1);
});
